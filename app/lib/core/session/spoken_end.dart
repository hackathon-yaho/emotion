/// 사용자가 **대화를 끝내겠다고 말했는지** 가린다 (F2-05, 2026-09-16 요청).
///
/// 말로 하는 서비스에서 종료만 손으로 하는 것은 앞뒤가 맞지 않는다. 다만
/// **잘못 끊는 비용이 크다** — 직장 이야기로 "이제 그만 좀 했으면 좋겠어"라고
/// 한 사람의 대화가 닫히는 것이 최악이다. 그래서 **갭·패턴과 같은 쪽**으로
/// 간다: 정밀도 우선, 애매하면 **침묵**(그냥 넘어간다). 걸리지 않아도 막다른
/// 길이 아니다 — 「대화 마치기」 버튼이 그대로 있다.
abstract final class SpokenEnd {
  /// **이 말이 대화를 끝내자는 뜻인가.**
  ///
  /// 두 갈래로 본다.
  ///
  /// - **분명한 표현**은 길이와 무관하게 받는다 — 「오늘은 여기까지」,
  ///   「대화 끝내자」처럼 **대화 자체**를 가리키는 말이다
  /// - **짧은 말의 맺음**만 받는 표현이 따로 있다 — 「그만하자」·「끝내자」는
  ///   주제를 두고도 쓰는 말이라, **문장이 짧고 그 말로 끝날 때만** 종료로
  ///   본다. "회의를 이제 그만하고 싶은데 팀장이…" 같은 문장은 걸리지 않는다
  static bool says(String text) {
    final t = _normalize(text);
    if (t.isEmpty) return false;
    if (_explicit.any(t.contains)) return true;
    // 짧은 말일 때만 맺음으로 판단한다. 길면 대화 속 화제일 가능성이 크다.
    if (t.length > _shortEnough) return false;
    return _closing.any(t.endsWith);
  }

  /// 공백·문장부호를 걷어낸다. 전사는 띄어쓰기가 고르지 않다.
  static String _normalize(String text) =>
      text.replaceAll(RegExp(r'[\s.,!?~…·"' "'" r']'), '');

  /// 이 길이 이하일 때만 맺음 표현을 종료로 본다.
  static const _shortEnough = 16;

  /// **대화 자체를 가리키는 말.** 길이와 무관하게 받는다.
  static const _explicit = [
    '오늘은여기까지',
    '오늘여기까지',
    '여기까지할게',
    '여기까지하자',
    '여기까지만할게',
    '여기까지만하자',
    '대화끝내',
    '대화그만',
    '대화종료',
    '이만마칠게',
    '이만끝낼게',
    '그만이야기할게',
  ];

  /// **짧은 말의 맺음일 때만** 종료로 보는 표현.
  static const _closing = [
    '그만하자',
    '그만할게',
    '그만할래',
    '그만하죠',
    '그만할까',
    '끝내자',
    '끝낼게',
    '끝낼래',
    '마칠게',
    '마치자',
    '여기까지',
  ];
}
